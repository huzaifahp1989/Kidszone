export function getQuotesForDay(date = new Date()): typeof islamicQuotesList {
  if (!islamicQuotesList.length) {
    throw new Error('No quotes available');
  }

  const dayIndex = Math.floor(date.getTime() / 86_400_000);
  const shuffledIndices = seededShuffle(dayIndex + 42, islamicQuotesList.length);
  const count = Math.min(5, islamicQuotesList.length);

  return shuffledIndices.slice(0, count).map((i) => islamicQuotesList[i]);
}

function seededShuffle(seed: number, length: number): number[] {
  const indices = Array.from({ length }, (_, i) => i);
  let s = seed >>> 0;
  for (let i = indices.length - 1; i > 0; i--) {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    const j = s % (i + 1);
    [indices[i], indices[j]] = [indices[j], indices[i]];
  }
  return indices;
}
